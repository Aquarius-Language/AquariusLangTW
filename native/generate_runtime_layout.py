"""Generate the guest memory layout shared by the Wasm emitters and runtime.c; no packages/network needed.

One table below is the source of truth. It produces
  AquariusCore/wasm/WasmRuntimeLayout.Generated.cs  (offsets the C# emitters and hosts use), and
  AquariusCore/wasm/runtime/layout.h                (_Static_assert(offsetof(...)) checks runtime.c includes),
so changing a struct in runtime.c without updating this table fails the runtime build, and editing a
generated file by hand fails `--check` (run by the architecture tests).

usage: python native/generate_runtime_layout.py [--check]
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent

# (C struct, C# prefix, [(C field, C# name, offset)], sizeof or None)
LAYOUT = [
    ('Value', 'Value', [('tag', 'Tag', 0), ('ref', 'Ref', 4), ('number', 'Number', 8)], 16),
    ('Text', 'Text', [('length', 'Length', 0), ('data', 'Data', 4)], None),
    ('Binding', 'Binding', [('name', 'Name', 0), ('hash', 'Hash', 4), ('value', 'Value', 8)], 24),
    ('Scope', 'Scope', [('outer', 'Outer', 0), ('bindings', 'Bindings', 4), ('count', 'Count', 8), ('capacity', 'Capacity', 12),
                        ('captured', 'Captured', 16), ('index', 'Index', 20), ('index_capacity', 'IndexCapacity', 24)], 28),
    ('ArrayStorage', 'ArrayStorage', [('references', 'References', 0), ('capacity', 'Capacity', 4), ('used', 'Used', 8),
                                      ('values', 'Values', 16)], 16),
    ('Array', 'Array', [('count', 'Count', 0), ('capacity', 'Capacity', 4), ('values', 'Values', 8), ('dirty_next', 'DirtyNext', 12),
                        ('dirty', 'Dirty', 16), ('exposed', 'Exposed', 20), ('storage', 'Storage', 24)], 28),
    ('Pair', 'Pair', [('key', 'Key', 0), ('value', 'Value', 16)], 32),
    ('Hash', 'Hash', [('count', 'Count', 0), ('capacity', 'Capacity', 4), ('pairs', 'Pairs', 8)], None),
    ('Function', 'Function', [('table', 'Table', 0), ('arity', 'Arity', 4), ('capacity', 'Capacity', 8), ('wrap_return', 'WrapReturn', 12),
                              ('parameters', 'Parameters', 16), ('constants', 'Constants', 20), ('numeric_table', 'NumericTable', 24),
                              ('recursive_name', 'RecursiveName', 28), ('locals', 'Locals', 32), ('flags', 'Flags', 36)], 40),
    ('Closure', 'Closure', [('program', 'Program', 0), ('function', 'Function', 4), ('scope', 'Scope', 8), ('context', 'Context', 12),
                            ('cache', 'Cache', 16), ('cache_era', 'CacheEra', 20)], 24),
    ('Frame', 'Frame', [('parent', 'Parent', 0), ('execution', 'Execution', 4), ('program', 'Program', 8), ('function', 'Function', 12),
                        ('scope', 'Scope', 16), ('loops', 'Loops', 20), ('pc', 'Pc', 24), ('sp', 'Sp', 28), ('returned', 'Returned', 32),
                        ('context', 'Context', 36), ('capacity', 'Capacity', 40), ('pending_base', 'PendingBase', 44),
                        ('pending_count', 'PendingCount', 48), ('binding_cache', 'BindingCache', 52), ('values', 'Values', 56)], None),
    ('Pending', 'Pending', [('dirty_arrays', 'DirtyArrays', 0), ('dirty_hashes', 'DirtyHashes', 4), ('released_arrays', 'ReleasedArrays', 8),
                            ('released_hashes', 'ReleasedHashes', 12), ('host_era', 'HostEra', 16)], 20),
    ('Execution', 'Execution', [('next', 'Next', 0), ('current', 'Current', 4), ('result', 'Result', 8), ('budget', 'Budget', 24),
                                ('status', 'Status', 28), ('numeric_depth_disabled', 'NumericDepthDisabled', 32), ('poll', 'Poll', 36),
                                ('numeric_closure', 'NumericClosure', 40), ('numeric_innermost', 'NumericInnermost', 44)], None),
]
# Value tags (runtime.c enum) and execution status codes (aqua_run results).
TAGS = [('Void', 0), ('Int', 1), ('Float', 2), ('Double', 3), ('Bool', 4), ('String', 5), ('Array', 6), ('Hash', 7), ('Closure', 8),
        ('Module', 9), ('Native', 10), ('Null', 11), ('Break', 12), ('Error', 13), ('Builtin', 14)]
STATUS = [('Running', 0), ('Yielded', 1), ('Suspended', 2), ('Failed', 3), ('Completed', 4)]


def csharp():
    lines = ['// Generated by native/generate_runtime_layout.py; do not edit.',
             'namespace AquariusLang.Wasm;', '',
             '/// <summary>Guest struct offsets, value tags and execution states shared with runtime.c (checked there by runtime/layout.h).</summary>',
             'internal static class RuntimeLayout', '{']
    for struct, prefix, fields, size in LAYOUT:
        members = [f'{prefix}{name} = {offset}' for _, name, offset in fields]
        if size is not None:
            members.append(f'{prefix}Size = {size}')
        lines.append(f'    /// <summary><c>{struct}</c></summary>')
        lines.append('    internal const int ' + ', '.join(members) + ';')
    lines.append('    internal const int ' + ', '.join(f'{name}Tag = {value}' for name, value in TAGS) + ';')
    lines.append('    internal const int ' + ', '.join(f'Status{name} = {value}' for name, value in STATUS) + ';')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def header():
    lines = ['/* Generated by native/generate_runtime_layout.py; do not edit. Included by runtime.c after its type definitions. */',
             '#ifndef AQUARIUS_RUNTIME_LAYOUT_H', '#define AQUARIUS_RUNTIME_LAYOUT_H']
    for struct, _, fields, size in LAYOUT:
        for field, _, offset in fields:
            lines.append(f'_Static_assert(offsetof({struct}, {field}) == {offset}, "{struct}.{field} moved: update native/generate_runtime_layout.py");')
        if size is not None:
            lines.append(f'_Static_assert(sizeof({struct}) == {size}, "{struct} size changed: update native/generate_runtime_layout.py");')
    for name, value in TAGS:
        c = {'Void': 'VOID', 'Int': 'INT', 'Float': 'FLOAT', 'Double': 'DOUBLE', 'Bool': 'BOOL', 'String': 'STRING', 'Array': 'ARRAY',
             'Hash': 'HASH', 'Closure': 'CLOSURE', 'Module': 'MODULE', 'Native': 'NATIVE', 'Null': 'NULL_VALUE',
             'Break': 'BREAK_VALUE', 'Error': 'ERROR', 'Builtin': 'BUILTIN'}[name]
        lines.append(f'_Static_assert({c} == {value}, "Value tag {c} changed: update native/generate_runtime_layout.py");')
    lines.append('#endif')
    return '\n'.join(lines) + '\n'


OUTPUTS = {
    ROOT / 'AquariusCore/wasm/WasmRuntimeLayout.Generated.cs': csharp,
    ROOT / 'AquariusCore/wasm/runtime/layout.h': header,
}

if __name__ == '__main__':
    check = '--check' in sys.argv[1:]
    stale = []
    for path, render in OUTPUTS.items():
        text = render()
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if check:
            if current is None or current.replace('\r\n', '\n') != text:
                stale.append(path.relative_to(ROOT).as_posix())
        elif current is None or current.replace('\r\n', '\n') != text:
            path.write_text(text, encoding='utf-8', newline='\n')
    if stale:
        print('Stale generated files (run python native/generate_runtime_layout.py): ' + ', '.join(stale))
        sys.exit(1)
    print('Runtime layout ' + ('is current.' if check else 'generated.'))
